export function SunflowerMark({
  size = 36,
  petalColor = "#F3C969",
  centerColor = "#4A3B63",
}: {
  size?: number;
  petalColor?: string;
  centerColor?: string;
}) {
  const angles = [0, 45, 90, 135, 180, 225, 270, 315];
  return (
    <svg width={size} height={size} viewBox="0 0 40 40" aria-hidden="true">
      {angles.map((angle) => (
        <g key={angle} transform={`rotate(${angle} 20 20)`}>
          <ellipse cx="20" cy="7" rx="4.2" ry="8.5" fill={petalColor} />
        </g>
      ))}
      <circle cx="20" cy="20" r="7.5" fill={centerColor} />
    </svg>
  );
}

